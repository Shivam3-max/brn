/**
 * Generates theme/snippets/art.liquid from scripts/art.mjs.
 *
 *   {% render 'art', key: 'i-tulsi', class: 'ink' %}
 *
 * Every stroke carries pathLength="1" so CSS can draw it in with a single
 * dashoffset transition, whatever its real length.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ART } from './art.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const body = Object.entries(ART).map(([key, parts]) => {
  const paths = parts.map((p) => {
    const { d, tf } = typeof p === 'string' ? { d: p } : p;
    return `<path pathLength="1" d="${d.replace(/\s+/g, ' ').trim()}"${tf ? ` transform="${tf}"` : ''}/>`;
  }).join('');
  return `{%- when '${key}' -%}${paths}`;
}).join('\n');

const out = `{%- comment -%}
  GENERATED by scripts/build-art.mjs from scripts/art.mjs — edit there, not here.
  ${Object.keys(ART).length} line drawings on a 120×120 grid.
  {% render 'art', key: 'i-tulsi', class: 'ink' %}
{%- endcomment -%}
<svg class="art {{ class }}" viewBox="0 0 120 120" aria-hidden="true" focusable="false">
{%- case key -%}
${body}
{%- else -%}<path pathLength="1" d="M60 14 V54 M60 54 C46 62 36 78 28 104 M60 54 C60 72 58 88 60 108 M60 54 C74 62 84 78 92 104"/>
{%- endcase -%}
</svg>
`;

fs.writeFileSync(path.join(ROOT, 'theme/snippets/art.liquid'), out);
console.log(`  art.liquid · ${Object.keys(ART).length} drawings`);
